#!/usr/bin/env node
/**
 * 将仓库根目录的静态网页资源同步到 app/www，并写入当前 App 版本信息。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const APP_DIR = path.resolve(__dirname, '..');
const ROOT_DIR = path.resolve(APP_DIR, '..');
const WWW_DIR = path.join(APP_DIR, 'www');

const pkg = JSON.parse(fs.readFileSync(path.join(APP_DIR, 'package.json'), 'utf8'));
const versionName = (process.env.APP_VERSION_NAME || pkg.version || '1.0.0').trim();
const versionCode = parseInt(process.env.APP_VERSION_CODE || String(pkg.versionCode || 1), 10) || 1;

function copyRecursive(src, dest) {
  const stat = fs.statSync(src);
  if (stat.isDirectory()) {
    fs.mkdirSync(dest, { recursive: true });
    for (const entry of fs.readdirSync(src)) {
      copyRecursive(path.join(src, entry), path.join(dest, entry));
    }
  } else {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(src, dest);
  }
}

fs.rmSync(WWW_DIR, { recursive: true, force: true });
fs.mkdirSync(WWW_DIR, { recursive: true });

const itemsToCopy = [
  'index.html',
  'manifest.json',
  'css',
  'js',
  'vendor',
  'icons'
];

for (const item of itemsToCopy) {
  const src = path.join(ROOT_DIR, item);
  if (fs.existsSync(src)) {
    copyRecursive(src, path.join(WWW_DIR, item));
  }
}

// 写入当前原生包版本号，供 js/app-updater.js 比对 version.json
const versionJs = `// Auto-generated by app/scripts/sync-web.mjs
window.APP_VERSION = ${JSON.stringify(versionName)};
window.APP_VERSION_CODE = ${versionCode};
`;
fs.writeFileSync(path.join(WWW_DIR, 'js', 'app-version.js'), versionJs, 'utf8');

// 确保 index.html 在 app-updater.js 之前加载 app-version.js
const indexPath = path.join(WWW_DIR, 'index.html');
let indexHtml = fs.readFileSync(indexPath, 'utf8');
if (!indexHtml.includes('js/app-version.js')) {
  indexHtml = indexHtml.replace(
    '<script src="js/app-updater.js"></script>',
    '<script src="js/app-version.js"></script>\n    <script src="js/app-updater.js"></script>'
  );
  fs.writeFileSync(indexPath, indexHtml, 'utf8');
}

console.log(`[sync-web] Synced web assets to app/www (v${versionName}, code=${versionCode})`);
